// RmlUi's SDL GPU shaders for the web build: reads their SPIR-V from RmlUi's generated headers
// (src/ThirdParty/RmlUi/Backends/RmlUi_SDL_GPU/compiled/shader_*.h), converts it to WGSL and writes
// src/source/Core/Platform/web/RmlUiShadersWgsl.h, which maps each SPIR-V blob (by hash) to its WGSL.
// Core/Platform/web/RmlUiGpuShaders.cpp hands that WGSL to SDL when RmlUi creates a shader.
//
//   node tools/web/rmlui-shaders-to-wgsl.mjs <naga-wasm dir>
//
// Run again whenever the RmlUi submodule's shaders change. See wgsl-convert.mjs for the conversion.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { convert, loadNaga } from "./wgsl-convert.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const compiledDir = join(root, "src", "ThirdParty", "RmlUi", "Backends", "RmlUi_SDL_GPU", "compiled");
const outFile = join(root, "src", "source", "Core", "Platform", "web", "RmlUiShadersWgsl.h");
const handWrittenDir = join(root, "tools", "web", "rmlui-wgsl");

const nagaDir = process.argv[2];
if (!nagaDir) {
  console.error("usage: node rmlui-shaders-to-wgsl.mjs <naga-wasm dir>");
  process.exit(2);
}
const naga = await loadNaga(nagaDir);

// FNV-1a, 64 bit; RmlUiGpuShaders.cpp computes the same over the SPIR-V RmlUi passes in.
function fnv1a64(bytes) {
  let hash = 0xcbf29ce484222325n;
  for (const byte of bytes) hash = BigInt.asUintN(64, (hash ^ BigInt(byte)) * 0x100000001b3n);
  return hash;
}

// Hand-written WGSL still has to be valid; naga checks it.
function checkHandWritten(naga, wgsl, name) {
  naga.validate(naga.parseWgsl(wgsl));
  return wgsl.replace(/^\/\/.*$/gm, "").trimStart();  // the backend's binding parser reads comments too
}

const entries = [];
const failed = [];
for (const file of readdirSync(compiledDir).filter((f) => /^shader_.*\.h$/.test(f)).sort()) {
  const name = file.replace(/\.h$/, "");
  const header = readFileSync(join(compiledDir, file), "utf8");
  const match = header.match(new RegExp(`${name}_spirv\\[\\]\\s*=\\s*\\{([^}]*)\\}`));
  if (!match) throw new Error(`${file}: no ${name}_spirv array`);
  const bytes = Uint8Array.from(match[1].split(",").map((s) => s.trim()).filter(Boolean).map((s) => parseInt(s, 16)));
  let wgsl;
  try {
    // A few shaders pass arrays between stages, which WGSL can't: those are written by hand.
    const handWritten = join(handWrittenDir, `${name}.wgsl`);
    wgsl = existsSync(handWritten) ? checkHandWritten(naga, readFileSync(handWritten, "utf8"), name)
                                   : convert(naga, bytes, name);
  } catch (error) {
    failed.push(name);
    console.log(`FAIL ${name}: ${error.formatted ?? error.message}`);
    continue;
  }
  if (wgsl.includes(")WGSL\"")) throw new Error(`${name}: WGSL contains the raw string delimiter`);
  entries.push({ name, size: bytes.length, hash: fnv1a64(bytes), wgsl });
  console.log(`ok   ${name}`);
}
if (failed.length) {
  console.error(`Not written: ${failed.join(", ")} failed`);
  process.exit(1);
}

const body = entries.map((e) =>
  `    {0x${e.hash.toString(16).padStart(16, "0")}ull, ${e.size}, "${e.name}",\n     R"WGSL(${e.wgsl})WGSL"},`).join("\n");
writeFileSync(outFile, `// Generated by tools/web/rmlui-shaders-to-wgsl.mjs from RmlUi's SDL GPU shaders. Don't edit by hand.
#pragma once

#include <cstddef>
#include <cstdint>

namespace mu::web
{
struct RmlUiWgslShader
{
    std::uint64_t spirvHash; // FNV-1a 64 of the SPIR-V blob RmlUi passes to SDL
    std::size_t spirvSize;
    const char* name;
    const char* wgsl;
};

inline constexpr RmlUiWgslShader RmlUiWgslShaders[] = {
${body}
};
} // namespace mu::web
`);
console.log(`Wrote ${outFile} (${entries.length} shaders)`);
