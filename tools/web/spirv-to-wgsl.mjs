// The game's shaders for the web build: src/shaders/compiled/<name>.spv to <name>.wgsl.
//
//   node tools/web/spirv-to-wgsl.mjs <naga-wasm dir> <out dir> <shader.spv>...
//
// See wgsl-convert.mjs for what changes on the way, and wgsl-soft-clip.mjs for the soft clip copies
// it also writes. naga-wasm (npm) is only needed on the machine that regenerates the files; the
// generated WGSL is checked in.

import { readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { convert, loadNaga } from "./wgsl-convert.mjs";
import { writeSoftClipVariant } from "./wgsl-soft-clip.mjs";

const [nagaDir, outDir, ...inputs] = process.argv.slice(2);
if (!nagaDir || !outDir || inputs.length === 0) {
  console.error("usage: node spirv-to-wgsl.mjs <naga-wasm dir> <out dir> <shader.spv>...");
  process.exit(2);
}
const naga = await loadNaga(nagaDir);
let failed = 0;
for (const input of inputs) {
  const name = basename(input).replace(/\.spv$/, "");
  try {
    const wgsl = convert(naga, readFileSync(input), name);
    writeFileSync(join(outDir, `${name}.wgsl`), `// Generated by tools/web/spirv-to-wgsl.mjs from ${name}.spv. Don't edit by hand.\n${wgsl}`);
    const softClip = writeSoftClipVariant(outDir, name, wgsl) ? " (+ soft clip)" : "";
    console.log(`ok   ${name}${softClip}`);
  } catch (error) {
    failed++;
    console.log(`FAIL ${name}: ${error.formatted ?? error.message}`);
  }
}
process.exitCode = failed ? 1 : 0;
