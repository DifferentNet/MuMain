// "Soft clip" copies of the game's WGSL, for graphics cards without the WebGPU feature
// clip-distances (ARM Mali, so the Pixel 9 and many other Android phones).
//
// Three vertex shaders cut away what is closer than 1 unit to the camera with a clip distance
// (clip-space w - 1). The copies pass that value to the fragment shader as an ordinary varying
// instead, and the fragment shaders that pair with them discard the pixel when it is below 0. The
// value is linear in clip space, so it changes sign where the clip plane cuts the triangle and the
// picture is the same. The renderer loads <name>_softclip.<stage>.wgsl when the page says the card
// has no clip distances (MuRendererSDLGpu.cpp).
//
//   node tools/web/wgsl-soft-clip.mjs src/shaders/compiled
//
// spirv-to-wgsl.mjs writes them too, whenever it regenerates the WGSL.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

// The fragment shaders the game's pipelines pair with the clip-distance vertex shaders. Every
// pairing must be soft clip on both sides: the fragment shader reads the varying the vertex
// shader writes.
export const SOFT_CLIP_SHADERS = [
  "basic_textured.vert", "skinned_textured.vert", "skinned_shadow.vert",
  "basic_textured.frag", "basic_textured_fog.frag", "skinned_lit.frag",
];
// The last location WebGPU always has (maxInterStageShaderVariables is at least 16), so it stays
// clear of the shaders' own varyings.
const SOFT_CLIP_LOCATION = 15;
const VARYING = "mu_softClip";

export function softClipName(name) {
  return name.replace(/\.(vert|frag)$/, "_softclip.$1");
}

function replaceOnce(text, pattern, replacement, what) {
  const matches = text.match(new RegExp(pattern.source, pattern.flags + "g")) || [];
  if (matches.length !== 1) throw new Error(`expected one ${what}, found ${matches.length}`);
  return text.replace(pattern, replacement);
}

function softClipVertex(wgsl) {
  let out = replaceOnce(wgsl, /^enable clip_distances;\r?\n/m, "", "'enable clip_distances'");
  out = replaceOnce(out, /@builtin\(clip_distances\) (\w+): array<f32, 1>,/,
                    `@location(${SOFT_CLIP_LOCATION}) $1: f32,`, "clip_distances output");
  // The entry point hands the one-element array to the output struct; pass its value instead.
  return replaceOnce(out, /(let _e\d+ = u0040_entryPointOutput_u002e_clipDist);/, "$1[0i];",
                     "clip distance read in the entry point");
}

function softClipFragment(wgsl) {
  return replaceOnce(wgsl, /(@fragment\s*\r?\nfn main\()([^{]*\{)/,
                     `$1@location(${SOFT_CLIP_LOCATION}) ${VARYING}: f32, $2\n` +
                     `    if (${VARYING} < 0f) {\n        discard;\n    }`,
                     "fragment entry point");
}

// The soft clip WGSL of shader <name> ("basic_textured.vert"), or null if it has none.
export function softClipVariant(name, wgsl) {
  if (!SOFT_CLIP_SHADERS.includes(name)) return null;
  if (wgsl.includes(`@location(${SOFT_CLIP_LOCATION})`)) {
    throw new Error(`${name} already uses location ${SOFT_CLIP_LOCATION}; pick another SOFT_CLIP_LOCATION`);
  }
  return name.endsWith(".vert") ? softClipVertex(wgsl) : softClipFragment(wgsl);
}

export function writeSoftClipVariant(dir, name, wgsl) {
  const variant = softClipVariant(name, wgsl);
  if (variant === null) return false;
  const header = `// Generated by tools/web/wgsl-soft-clip.mjs from ${name}.wgsl. Don't edit by hand.\n`;
  const body = variant.replace(/^\/\/ Generated by [^\n]*\n/, "");
  writeFileSync(join(dir, `${softClipName(name)}.wgsl`), header + body);
  return true;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const dir = process.argv[2];
  if (!dir) {
    console.error("usage: node wgsl-soft-clip.mjs <folder with the game's .wgsl files>");
    process.exit(2);
  }
  let failed = 0;
  for (const name of SOFT_CLIP_SHADERS) {
    try {
      writeSoftClipVariant(dir, name, readFileSync(join(dir, `${name}.wgsl`), "utf8"));
      console.log(`ok   ${softClipName(name)}`);
    } catch (error) {
      failed++;
      console.log(`FAIL ${name}: ${error.message}`);
    }
  }
  process.exitCode = failed ? 1 : 0;
}
